#!/usr/bin/env node
/**
 * Generate src/data/z-moves.js from Pokemon Showdown's move table
 * (tools/cache/showdown-moves.json — see fix-stat-changes.cjs, which fetches it).
 *
 * The type-based Z-Moves ("isZ" crystals), the base-power -> Z-power curve and
 * the per-status-move Z-boosts all live in Showdown, so derive them once and
 * commit the result. Re-run after the cache is refreshed:
 *
 *   node tools/generate-z-move-data.cjs
 */
const fs = require('fs')
const path = require('path')

const CACHE = path.join(__dirname, 'cache', 'showdown-moves.json')
const OUT = path.join(__dirname, '..', 'src', 'data', 'z-moves.js')

const moves = JSON.parse(fs.readFileSync(CACHE, 'utf8'))

/** The 18 type crystals (the species-specific ones are not modelled). */
const TYPE_CRYSTALS = new Set([
  'normaliumz',
  'firiumz',
  'wateriumz',
  'electriumz',
  'grassiumz',
  'iciumz',
  'fightiniumz',
  'poisoniumz',
  'groundiumz',
  'flyiniumz',
  'psychiumz',
  'buginiumz',
  'rockiumz',
  'ghostiumz',
  'dragoniumz',
  'darkiniumz',
  'steeliumz',
  'fairiumz',
])

const STAT_MAP = {
  atk: 'attack',
  def: 'defense',
  spa: 'spAttack',
  spd: 'spDefense',
  spe: 'speed',
  accuracy: 'accuracy',
  evasion: 'evasion',
}

const toCamel = (/** @type {string} */ name) => {
  const parts = name
    .replace(/'/g, '')
    .replace(/[^a-zA-Z0-9]+/g, ' ')
    .trim()
    .split(' ')
  return (
    parts[0].toLowerCase() +
    parts
      .slice(1)
      .map((part) => part.charAt(0).toUpperCase() + part.slice(1).toLowerCase())
      .join('')
  )
}

/** The crystal id ('firiumz') to the game's item key ('firiumZ'). */
const crystalKey = (/** @type {string} */ id) => id.slice(0, -1) + 'Z'

const zMoveByType = {},
  crystalByType = {},
  statusBoosts = {},
  statusEffects = {}
for (const [id, move] of Object.entries(moves)) {
  if (!move.isZ || !TYPE_CRYSTALS.has(move.isZ)) continue
  zMoveByType[move.type] = toCamel(move.name)
  crystalByType[move.type] = crystalKey(move.isZ)
}
for (const [id, move] of Object.entries(moves)) {
  if (!move.zMove || move.category !== 'Status') continue
  const key = toCamel(move.name)
  if (move.zMove.boost) {
    const changes = {}
    for (const [stat, delta] of Object.entries(move.zMove.boost)) changes[STAT_MAP[stat] ?? stat] = delta
    statusBoosts[key] = changes
  }
  if (move.zMove.effect) statusEffects[key] = move.zMove.effect
}

const header = `// Generated by tools/generate-z-move-data.cjs — do not edit by hand.
// Z-Crystal data: the type-based Z-Moves, the base-power curve and the boosts
// a status move gains when powered by a matching Z-Crystal.

`
const body =
  `/** @type {Record<string, string>} Type -> its type-based Z-Move key. */\n` +
  `export const Z_MOVE_BY_TYPE = ${JSON.stringify(zMoveByType, null, 2)}\n\n` +
  `/** @type {Record<string, string>} Type -> the Z-Crystal item that powers it. */\n` +
  `export const Z_CRYSTAL_BY_TYPE = ${JSON.stringify(crystalByType, null, 2)}\n\n` +
  `/** @type {Record<string, string>} Z-Crystal item -> its type. */\n` +
  `export const Z_CRYSTAL_TYPE = Object.fromEntries(\n  Object.entries(Z_CRYSTAL_BY_TYPE).map(([type, crystal]) => [crystal, type])\n)\n\n` +
  `/** @type {Record<string, Record<string, number>>} Status move key -> the stat stages a Z-Crystal adds. */\n` +
  `export const Z_STATUS_BOOSTS = ${JSON.stringify(statusBoosts, null, 2)}\n\n` +
  `/** @type {Record<string, string>} Status move key -> its special Z-effect (clearnegativeboost, crit2, heal, ...). */\n` +
  `export const Z_STATUS_EFFECTS = ${JSON.stringify(statusEffects, null, 2)}\n\n` +
  `/**\n * The base power of a type-based Z-Move, from the base move's power.\n * @param {number} basePower\n * @returns {number}\n */\n` +
  `export function zMoveBasePower(basePower) {\n` +
  `  if (basePower <= 0) return 100\n` +
  `  if (basePower >= 140) return 200\n` +
  `  if (basePower >= 130) return 195\n` +
  `  if (basePower >= 120) return 190\n` +
  `  if (basePower >= 110) return 185\n` +
  `  if (basePower >= 100) return 180\n` +
  `  if (basePower >= 90) return 175\n` +
  `  if (basePower >= 80) return 160\n` +
  `  if (basePower >= 70) return 140\n` +
  `  if (basePower >= 60) return 120\n` +
  `  return 100\n` +
  `}\n`

fs.writeFileSync(OUT, header + body)
console.log(
  `wrote ${path.relative(process.cwd(), OUT)}: ${Object.keys(zMoveByType).length} Z-Moves, ` +
    `${Object.keys(statusBoosts).length} status boosts, ${Object.keys(statusEffects).length} status effects`
)
